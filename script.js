function getInitialLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  if (queryLanguage === "ru" || queryLanguage === "tt") return queryLanguage;

  try {
    const savedLanguage = window.localStorage.getItem("snt-language");
    if (savedLanguage === "ru" || savedLanguage === "tt") return savedLanguage;
  } catch {
    // The page also works when storage is blocked.
  }

  return "ru";
}

function translate(key, replacements = {}) {
  const fallback = translations.ru[key] ?? key;
  const value = translations[language]?.[key] ?? fallback;
  return Object.entries(replacements).reduce(
    (result, [name, replacement]) => result.replaceAll(`{${name}}`, replacement),
    value,
  );
}

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.documentElement.dataset.lang = language;
  document.title = translate("pageTitle");
  document.querySelector('meta[name="description"]')?.setAttribute("content", translate("pageDescription"));

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = translate(element.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  try {
    window.localStorage.setItem("snt-language", language);
  } catch {
    // Language switching does not depend on storage.
  }

  updateDynamicHero();
}

function getMoscowDateParts(now = new Date()) {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Europe/Moscow",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).formatToParts(now);
  const values = Object.fromEntries(parts.map(({ type, value }) => [type, value]));
  const key = `${values.year}-${values.month}-${values.day}`;
  const utcDay = new Date(`${key}T12:00:00Z`).getUTCDay();

  return {
    key,
    year: Number(values.year),
    month: Number(values.month),
    day: Number(values.day),
    hour: Number(values.hour),
    minute: Number(values.minute),
    utcDay,
  };
}

function formatToday(parts) {
  const weekdays = language === "tt"
    ? ["якшәмбе", "дүшәмбе", "сишәмбе", "чәршәмбе", "пәнҗешәмбе", "җомга", "шимбә"]
    : ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"];
  const months = language === "tt"
    ? ["гыйнвар", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]
    : ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];
  const label = `${weekdays[parts.utcDay]}, ${parts.day} ${months[parts.month - 1]}`;
  return label.charAt(0).toUpperCase() + label.slice(1);
}

function formatUpdatedDate(value) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  const locale = language === "tt" ? "tt-RU" : "ru-RU";
  return new Intl.DateTimeFormat(locale, {
    timeZone: "Europe/Moscow",
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  }).format(date);
}

function getDayState() {
  const parts = getMoscowDateParts();
  const calendarDay = calendar.days?.[parts.key];
  const weekendByWeekday = parts.utcDay === 0 || parts.utcDay === 6;
  const isWorking = typeof calendarDay?.isWorking === "boolean"
    ? calendarDay.isWorking
    : !weekendByWeekday;
  const isHoliday = Boolean(calendarDay?.holiday);
  const startHour = isWorking ? 6 : 9;
  const minutesNow = parts.hour * 60 + parts.minute;
  const isAllowedNow = minutesNow >= startHour * 60 && minutesNow < 22 * 60;

  return {
    ...parts,
    calendarDay,
    isWorking,
    isHoliday,
    startHour,
    isAllowedNow,
    isBeforeWindow: minutesNow < startHour * 60,
  };
}

function getDayType(state) {
  if (state.isHoliday) return translate("holidayDay");
  return state.isWorking ? translate("workingDay") : translate("weekendDay");
}

function setText(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.textContent = value;
}

function setHtml(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.innerHTML = value;
}

function updateDynamicHero() {
  currentDayState = getDayState();
  const state = currentDayState;
  const dayType = getDayType(state);
  const start = String(state.startHour).padStart(2, "0");
  const hero = document.querySelector("[data-hero]");

  hero?.classList.remove("is-loading");
  hero?.classList.toggle("is-allowed", state.isAllowedNow);
  hero?.classList.toggle("is-quiet", !state.isAllowedNow);

  setText("[data-today-label]", formatToday(state));
  setText("[data-hero-title]", translate("today"));
  setText("[data-hero-status]", translate(state.isAllowedNow ? "canNoiseNow" : "quietNow"));
  setText("[data-start-time]", `${start}:00`);
  setText("[data-hero-window]", `${start}:00–22:00`);
  setText("[data-hero-rule-title]", translate(state.isWorking ? "ruleWorkday" : "ruleWeekend"));
  setText("[data-hero-rule-time]", translate("fromTo", { start }));
  setText("[data-neighbor-answer]", translate("neighborAnswer", { dayType, start }));

  const leadKey = state.isAllowedNow ? "leadAllowed" : state.isBeforeWindow ? "leadBefore" : "leadAfter";
  setHtml("[data-hero-lead]", translate(leadKey, { dayType, start }));
  setText("[data-hero-caption]", translate(state.isWorking ? "captionWorkday" : "captionWeekend"));

  const updatedDate = formatUpdatedDate(calendar.generatedAt);
  const calendarMessage = state.calendarDay && updatedDate
    ? translate("calendarUpdated", { date: updatedDate })
    : translate("calendarWeekdayFallback");
  setText("[data-calendar-state]", calendarMessage);
  const fallback = document.querySelector("[data-i18n=\"calendarFallback\"]");
  if (fallback) fallback.hidden = true;
}

function showToast(message) {
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add("visible");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove("visible"), 2400);
}

async function copyAnswer() {
  const answerText = document.querySelector("[data-neighbor-answer]")?.textContent.trim() ?? "";

  try {
    await navigator.clipboard.writeText(answerText);
    showToast(translate("copied"));
  } catch {
    const textArea = document.createElement("textarea");
    textArea.value = answerText;
    textArea.setAttribute("readonly", "");
    textArea.style.position = "fixed";
    textArea.style.opacity = "0";
    document.body.append(textArea);
    textArea.select();
    const copied = document.execCommand("copy");
    textArea.remove();
    showToast(translate(copied ? "copied" : "copyFailed"));
  }
}

